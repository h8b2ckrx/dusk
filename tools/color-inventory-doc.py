#!/usr/bin/env python3
"""Write docs/inventory-shell-colors.md (for the owner) from the color table
(design decision 22).

Usage: color-inventory-doc.py docs/inventory-shell-colors.tsv > docs/inventory-shell-colors.md
"""
import collections
import sys

# The main surfaces shown in the summary: (surface, selector, property).
KEY = [
    ("Menus", ".popup-menu-content", "background-color"),
    ("Menus", ".popup-menu-item:hover", "background-color"),
    ("Menus", ".popup-menu-item:active", "background-color"),
    ("Menus", ".popup-sub-menu", "background-color"),
    ("Quick settings", ".quick-toggle-menu", "background-color"),
    ("Quick settings", ".button", "background-color"),
    ("Quick settings", ".button:hover", "background-color"),
    ("Notifications", ".message", "background-color"),
    ("Notifications", ".message:hover", "background-color"),
    ("Notifications", ".message:second-in-stack", "background-color"),
    ("Date menu", ".events-button", "background-color"),
    ("Date menu", ".world-clocks-button", "background-color"),
    ("Dialogs", ".modal-dialog", "background-color"),
    ("Dialogs", ".modal-dialog .modal-dialog-button-box .modal-dialog-button", "background-color"),
    ("OSDs", ".osd-window", "background-color"),
    ("Switchers", ".switcher-list", "background-color"),
    ("Tooltips", ".dash-label", "background-color"),
    ("Screenshot", ".screenshot-ui-panel", "background-color"),
    ("Scroll bars", "StScrollBar > .vhandle", "background-color"),
]

SECTIONS = [
    ("derived", "Derived rows (please check)",
     "New in 26.04, so 24.04 has no value of its own: 26.04's formula with 24.04's colors swapped in."),
    ("renamed", "Renamed rows", "Same element, different selector in 24.04: its exact 24.04 value."),
    ("unset", "Unset rows", "24.04 drew nothing there."),
]


def main():
    rows = [l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if l.strip() and not l.startswith("# ")]
    by = collections.defaultdict(dict)
    for mode, sel, prop, new, old, src, _, _ in rows:
        for m in (["dark", "light"] if mode == "both" else [mode]):
            by[(sel, prop)][m] = (new, old)
    n = collections.Counter(r[5] for r in rows)
    out = [
        "# Shell pop-up color inventory",
        "",
        "Approved by the owner (design decision 22, Task 3 of",
        "[the plan](2026-10-29-dusk-shell-colors-plan.md)) and built: all three chunks are on. The dialog",
        "buttons rejoined it when the dialogs went back to 26.04's layout (decision 23). Generated by",
        "`tools/color-inventory-doc.py`.",
        "",
        "- **What:** every color rule Yaru 26.04 has for the Shell's floating surfaces, in dark and light,",
        "  next to Yaru 24.04's value for the same thing. Built by `tools/shell-color-inventory.sh` into",
        "  [inventory-shell-colors.tsv](inventory-shell-colors.tsv), which has every row.",
        f"- **Rows:** {len(rows)} ({sum(1 for r in rows if r[0] == 'both')} the same in both modes). "
        "Where the 24.04 value comes from:",
        f"  - **{n['same']} same:** 24.04 has the same rule; its exact value.",
        f"  - **{n['renamed']} renamed:** 24.04 has the element under another selector (scroll bar handles, the",
        "    password dialog's labels); its exact value. [The renames](inventory-shell-colors-renames.tsv).",
        f"  - **{n['unset']} unset:** 24.04 has the element but drew no background, border or shadow there: none.",
        f"  - **{n['derived']} derived:** new in 26.04 (notification groups and stacks, CSS-drawn switches and",
        "    check boxes, the quick-toggle arrow button…): 26.04's own formula with 24.04's colors swapped in.",
        "    [Dark palette](inventory-shell-colors-palette-dark.tsv),"
        " [light palette](inventory-shell-colors-palette-light.tsv).",
        f"  - **{n['accent']} accent:** uses your accent color (focus rings, checked toggles, the selected day…):",
        "    26.04's formula stays, so it follows the Settings picker; only a surface color inside it becomes",
        "    24.04's.",
        f"  - **{n['keep']} keep:** an out-of-scope rule (lock screen, Blur my Shell's surfaces, the overview's",
        "    search entry…) that one of these would otherwise override. It keeps today's value: no visible change.",
        "- **Chunks:** 1 menus and quick settings, with the buttons, switches, entries, check boxes and scroll",
        "  bars drawn on them (so those change everywhere they appear); 2 notifications and the date menu; 3",
        "  dialogs (in 26.04's own layout), OSDs, Alt+Tab, tooltips and the screenshot panel.",
        "- **Not included** (design §3): the top bar, dock, overview and app grid, Blur my Shell's search cards and",
        "  folder pop-up, the lock and login screens, the on-screen keyboard, Looking Glass, other extensions'",
        "  panels.",
        "",
        "## The main surfaces",
        "",
        "| Surface | Element | Dark now → 24.04 | Light now → 24.04 |",
        "|---|---|---|---|",
    ]
    for surface, sel, prop in KEY:
        d = by.get((sel, prop), {})
        cell = lambda m: f"`{d[m][0]}` → `{d[m][1]}`" if m in d else "—"
        out.append(f"| {surface} | `{sel}` background | {cell('dark')} | {cell('light')} |")
    for src, title, why in SECTIONS:
        out += ["", f"## {title}", "", why, "", "| Mode | Selector | Property | 26.04 | 24.04 |", "|---|---|---|---|---|"]
        out += [f"| {mode} | `{sel}` | {prop} | `{new}` | `{old}` |"
                for mode, sel, prop, new, old, s, _, _ in rows if s == src]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
