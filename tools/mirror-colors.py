#!/usr/bin/env python3
"""Generate the Shell pop-up color partials from docs/inventory-shell-colors.tsv
(design decision 22).

Usage: mirror-colors.py TSV rules   > src/_shell-colors.scss
       mirror-colors.py TSV values  > src/_shell-color-values.scss

rules: every row as a rule with its selector (Yaru 26.04's, or 24.04's for
an added row), in the inventory's order, its value
`shell-color-value("<token>")` with the !important its 24.04 value carries.
Consecutive rows of one chunk share an `@if shell-colors-on(N)` block, so a
chunk that's switched off emits nothing; a row for one mode only has its own
`@if $mode == …`.

values: `$shell-color-values: (dark: (…), light: (…))`, each row's token and
24.04 value (unquoted as is, !important dropped).
"""
import os
import sys

CHUNK_NAMES = {
    0: "Out-of-scope rules one of these would override, kept at their stock value",
    1: "Menus and quick settings, and the controls drawn on them",
    2: "Notifications and the date menu",
    3: "Dialogs, OSDs, switchers, tooltips and the screenshot panel",
}


def rows(path):
    return [l.rstrip("\n").split("\t") for l in open(path) if l.strip() and not l.startswith("# ")]


def header(tsv):
    name = os.path.relpath(tsv, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    return [f"// Generated by tools/mirror-colors.py from {name}: don't edit by hand.",
            "// Shell pop-up colors like Ubuntu 24.04 (design decision 22)."]


def groups(items, key):
    """Consecutive runs of items with the same key: [(key, [items])]."""
    out = []
    for item in items:
        k = key(item)
        if out and out[-1][0] == k:
            out[-1][1].append(item)
        else:
            out.append((k, [item]))
    return out


def rules(table, tsv):
    out = header(tsv) + ["// Yaru 26.04's own selectors, in Yaru's order; values from",
                         "// src/_shell-color-values.scss; chunks switch on in src/_tokens.scss."]
    for chunk, block in groups(table, lambda r: int(r[7])):
        out += ["", f"// {CHUNK_NAMES[chunk]}.", f"@if shell-colors-on({chunk}) {{"]
        for sel, decls in groups(block, lambda r: r[1]):
            out.append(f"  {sel} {{")
            for mode, _, prop, _, old, _, token, _ in decls:
                important = " !important" if "!important" in old else ""
                decl = f'{prop}: shell-color-value("{token}"){important};'
                out.append(f"    {decl}" if mode == "both" else f"    @if $mode == {mode} {{ {decl} }}")
            out.append("  }")
        out.append("}")
    return "\n".join(out) + "\n"


def values(table, tsv):
    out = header(tsv) + ["// Each inventory row's Yaru 24.04 value, per mode (src/shell.scss: shell-color-value)."]
    out.append("$shell-color-values: (")
    for mode in ("dark", "light"):
        out.append(f"  {mode}: (")
        seen = set()
        for m, sel, prop, new, old, source, token, chunk in table:
            if m in ("both", mode) and token not in seen:
                seen.add(token)
                value = " ".join(old.replace("!important", "").split()).replace('"', '\\"')
                out.append(f'    "{token}": unquote("{value}"),')
        out.append("  ),")
    out.append(");")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3 or sys.argv[2] not in ("rules", "values"):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    table = rows(sys.argv[1])
    print((rules if sys.argv[2] == "rules" else values)(table, sys.argv[1]), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
