def expression(stock, token):
    """The Sass value for a stock value under a token."""
    def swap(m):
        if float(m.group(1)) == 0:
            return "0"
        return f"#{{$radius-{token}}}"
    return LENGTH.sub(swap, stock)


def main():
    if len(sys.argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    rows = [line.rstrip("\n").split("\t") for line in open(sys.argv[1])
            if line.strip() and not line.startswith("#")]

    blocks = []  # [token, property, value, [selectors]]
    for selector, prop, stock, token in rows:
        value = expression(stock, token)
        if blocks and blocks[-1][1:3] == [prop, value]:
            blocks[-1][3].append(selector)
        else:
            blocks.append([token, prop, value, [selector]])

    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source = os.path.relpath(os.path.abspath(sys.argv[1]), repo)
    print(f"// Generated by tools/mirror-radius.py from {source}; don't edit by hand.")
    print("// To change a value, edit its token in src/_tokens.scss; to change which")
    print("// token a rule uses, edit the inventory's last column and regenerate.")
    for token, prop, value, selectors in blocks:
        print()
        print(f"// {DESCRIPTIONS[token]}")
        print(",\n".join(selectors) + " {")
        print(f"  {prop}: {value};")
        print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
